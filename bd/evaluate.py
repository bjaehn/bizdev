"""Eval harness: run a scanner over a human-verified gold file and report how it did.

tests/gold.csv columns: account, domain, expected_type, expected_date, expected_url.
  - One row per expected signal; an account may have several rows.
  - expected_type = `none` marks an account where NO signal is expected.
  - A BLANK expected_type is an error (an unfilled template row must never read as "no signal").
The gold file is human-verified ground truth; it is never generated by this tool.
"""

from __future__ import annotations

import csv
import json
from collections import OrderedDict
from collections.abc import Callable
from dataclasses import asdict, dataclass, field
from datetime import date
from pathlib import Path

from bd.accounts import Account, normalize_domain
from bd.models import SIGNAL_TYPES
from bd.scanners.base import AcceptedSignal, Rejection, ScanOutcome
from bd.urls import normalize_url

GOLD_COLUMNS = ["account", "domain", "expected_type", "expected_date", "expected_url"]


class GoldError(ValueError):
    pass


@dataclass(frozen=True)
class GoldRow:
    account: str
    domain: str
    expected_type: str | None  # None => no signal expected
    expected_date: date | None
    expected_url: str | None


def load_gold(path: str | Path) -> list[GoldRow]:
    p = Path(path)
    if not p.exists():
        raise GoldError(f"{p} not found. Create it from tests/gold.template.csv with verified values.")
    rows: list[GoldRow] = []
    errs: list[str] = []
    with open(p, newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        cols = [c.strip() for c in (reader.fieldnames or [])]
        if cols != GOLD_COLUMNS:
            raise GoldError(f"header must be exactly: {','.join(GOLD_COLUMNS)}")
        for n, r in enumerate(reader, start=2):
            g = lambda k: (r.get(k) or "").strip()  # noqa: E731
            if not g("account"):
                errs.append(f"row {n}: account is required")
                continue
            t = g("expected_type").lower()
            if not t:
                errs.append(f"row {n} ({g('account')}): expected_type is blank - fill it in, or write `none` "
                            "if no signal is expected")
                continue
            if t == "none":
                if g("expected_date") or g("expected_url"):
                    errs.append(f"row {n} ({g('account')}): `none` rows must leave date and url blank")
                    continue
                rows.append(GoldRow(g("account"), normalize_domain(g("domain")), None, None, None))
                continue
            if t not in SIGNAL_TYPES:
                errs.append(f"row {n} ({g('account')}): unknown expected_type {t!r}")
                continue
            try:
                d = date.fromisoformat(g("expected_date"))
            except ValueError:
                errs.append(f"row {n} ({g('account')}): expected_date must be YYYY-MM-DD")
                continue
            if not g("expected_url").startswith(("http://", "https://")):
                errs.append(f"row {n} ({g('account')}): expected_url must be an http(s) URL")
                continue
            rows.append(GoldRow(g("account"), normalize_domain(g("domain")), t, d, g("expected_url")))
    if errs:
        raise GoldError("\n".join(errs))
    if not rows:
        raise GoldError("gold file has no rows")
    return rows


@dataclass
class RowResult:
    account: str
    expected_type: str
    expected_date: str
    status: str  # found | wrong_date | missed
    got_date: str | None = None
    got_url: str | None = None
    url_match: bool | None = None
    date_diff_days: int | None = None


@dataclass
class AccountResult:
    account: str
    expects_none: bool
    rows: list[RowResult] = field(default_factory=list)
    false_positives: list[dict] = field(default_factory=list)  # accepted signals on a `none` account
    unexpected: list[dict] = field(default_factory=list)       # accepted but not in gold (review by hand)
    fabricated: list[dict] = field(default_factory=list)       # URL not in the search tool's results
    unreachable: list[dict] = field(default_factory=list)      # URL did not resolve
    blocked: list[dict] = field(default_factory=list)          # URL on the blocked list
    other_rejections: list[dict] = field(default_factory=list)
    error: str | None = None
    tokens: int = 0
    web_searches: int = 0


@dataclass
class EvalReport:
    as_of: str
    tolerance_days: int
    accounts: list[AccountResult]

    def totals(self) -> dict[str, int]:
        rows = [r for a in self.accounts for r in a.rows]
        none_accts = [a for a in self.accounts if a.expects_none]
        return {
            "expected_signals": len(rows),
            "found": sum(r.status in ("found", "wrong_date") for r in rows),
            "found_exact_date": sum(r.status == "found" for r in rows),
            "wrong_date": sum(r.status == "wrong_date" for r in rows),
            "missed": sum(r.status == "missed" for r in rows),
            "no_signal_accounts": len(none_accts),
            "no_signal_clean": sum(not a.false_positives and not a.error for a in none_accts),
            "false_positives": sum(len(a.false_positives) for a in none_accts),
            "unexpected_extra": sum(len(a.unexpected) for a in self.accounts),
            "fabricated_urls": sum(len(a.fabricated) for a in self.accounts),
            "unreachable_urls": sum(len(a.unreachable) for a in self.accounts),
            "blocked_urls": sum(len(a.blocked) for a in self.accounts),
            "accounts_with_errors": sum(bool(a.error) for a in self.accounts),
            "tokens": sum(a.tokens for a in self.accounts),
            "web_searches": sum(a.web_searches for a in self.accounts),
        }

    def to_json(self) -> str:
        return json.dumps({"as_of": self.as_of, "tolerance_days": self.tolerance_days,
                           "totals": self.totals(), "accounts": [asdict(a) for a in self.accounts]},
                          indent=2, sort_keys=True)

    def render(self) -> str:
        t = self.totals()
        L = [f"Eval as of {self.as_of} (date tolerance {self.tolerance_days}d)", ""]
        L.append(f"Expected signals : {t['expected_signals']}")
        L.append(f"  found          : {t['found']}   (exact date {t['found_exact_date']}, wrong date {t['wrong_date']})")
        L.append(f"  missed         : {t['missed']}")
        L.append(f"No-signal accts  : {t['no_signal_accounts']}   (clean {t['no_signal_clean']}, "
                 f"false positives {t['false_positives']})")
        L.append(f"Fabricated URLs  : {t['fabricated_urls']}   (not in search results; rejected)")
        L.append(f"Unreachable URLs : {t['unreachable_urls']}   (did not resolve; rejected)")
        L.append(f"Blocked-domain   : {t['blocked_urls']}   (LinkedIn/paywalled; rejected)")
        L.append(f"Unexpected extra : {t['unexpected_extra']}   (accepted, not in gold - review by hand)")
        L.append(f"Account errors   : {t['accounts_with_errors']}")
        L.append(f"Tokens / searches: {t['tokens']:,} / {t['web_searches']}")
        L.append("")
        for a in self.accounts:
            tag = "ERROR " + a.error if a.error else ""
            L.append(f"- {a.account} {tag}".rstrip())
            for r in a.rows:
                extra = ""
                if r.status == "wrong_date":
                    extra = f"  expected {r.expected_date}, got {r.got_date} ({r.date_diff_days:+d}d)"
                elif r.status == "found":
                    extra = f"  {r.got_date}" + ("" if r.url_match else "  (different URL than gold)")
                L.append(f"    [{r.status:<10}] {r.expected_type}{extra}")
            for fp in a.false_positives:
                L.append(f"    [false_pos ] {fp['type']} {fp['event_date']} {fp['url']}")
            for u in a.unexpected:
                L.append(f"    [unexpected] {u['type']} {u['event_date']} {u['url']}")
            for k, label in (("fabricated", "fabricated"), ("unreachable", "unreachable"), ("blocked", "blocked")):
                for x in getattr(a, k):
                    L.append(f"    [{label:<10}] {x['type']} {x['url']} {x.get('reason', '')}".rstrip())
        return "\n".join(L)


def _sig(s: AcceptedSignal) -> dict:
    e = s.extract
    return {"type": e.type, "event_date": e.event_date.isoformat(), "url": e.source_url,
            "confidence": e.confidence}


def _rej(r: Rejection) -> dict:
    return {"type": r.type, "url": r.url, "reason": r.reason}


def evaluate(gold: list[GoldRow], scan: Callable[[Account, date], ScanOutcome], as_of: date,
             tolerance_days: int = 0, limit: int | None = None) -> EvalReport:
    by_account: OrderedDict[str, list[GoldRow]] = OrderedDict()
    for g in gold:
        by_account.setdefault(g.account, []).append(g)
    names = list(by_account)[:limit] if limit else list(by_account)

    results: list[AccountResult] = []
    for i, name in enumerate(names, start=1):
        rows = by_account[name]
        domain = rows[0].domain or None
        outcome = scan(Account(id=-i, name=name, domain=domain), as_of)
        res = AccountResult(account=name, expects_none=all(r.expected_type is None for r in rows),
                            error=outcome.error, tokens=outcome.usage.total_tokens,
                            web_searches=outcome.usage.web_searches)
        for r in outcome.rejections:
            bucket = ("fabricated" if r.reason == "url_not_retrieved"
                      else "unreachable" if r.reason.startswith("unreachable")
                      else "blocked" if r.reason == "blocked_domain" else "other_rejections")
            getattr(res, bucket).append(_rej(r))

        unused = list(outcome.signals)
        if res.expects_none:
            res.false_positives = [_sig(s) for s in unused]
        else:
            for g in rows:
                assert g.expected_type and g.expected_date and g.expected_url
                cands = [s for s in unused if s.extract.type == g.expected_type]
                rr = RowResult(account=name, expected_type=g.expected_type,
                               expected_date=g.expected_date.isoformat(), status="missed")
                if cands:
                    want = normalize_url(g.expected_url)
                    best = (next((s for s in cands if normalize_url(s.extract.source_url) == want), None)
                            or next((s for s in cands if s.extract.event_date == g.expected_date), None)
                            or cands[0])
                    unused.remove(best)
                    diff = (best.extract.event_date - g.expected_date).days
                    rr.got_date = best.extract.event_date.isoformat()
                    rr.got_url = best.extract.source_url
                    rr.url_match = normalize_url(best.extract.source_url) == want
                    rr.date_diff_days = diff
                    rr.status = "found" if abs(diff) <= tolerance_days else "wrong_date"
                res.rows.append(rr)
            res.unexpected = [_sig(s) for s in unused]
        results.append(res)
    return EvalReport(as_of=as_of.isoformat(), tolerance_days=tolerance_days, accounts=results)
